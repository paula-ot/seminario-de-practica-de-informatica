    private void btnSeleccionarArchivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeleccionarArchivoActionPerformed
        //abre ventana del SO para buscar archivos
        int resultado = jFileChooser1.showOpenDialog(this);
        if (resultado == javax.swing.JFileChooser.APPROVE_OPTION){
            archivoSeleccionado = jFileChooser1.getSelectedFile();
            //muestra la ruta del archivo
            lblRutaArchivo.setText(archivoSeleccionado.getAbsolutePath());
            //validar extension del archivo
            if (archivoSeleccionado.getName().toLowerCase().endsWith(".log")){
                lblEstadoValidacion.setText("Archivo validado correctamente. Listo para procesar.");
                //habilita boton procesar
                btnConfirmarProcesar.setEnabled(true);
            } else{
                lblEstadoValidacion.setText("Error: El archivo seleccionado no es un archivo .log");
                btnConfirmarProcesar.setEnabled(false);                
            }
        }
    }//GEN-LAST:event_btnSeleccionarArchivoActionPerformed

    private void btnConfirmarProcesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarProcesarActionPerformed
        try{
            //importa y valida lineas del log cargandolas en memoria
            RegistroEventoTemp eventoTemp = controlador.importarArchivo(archivoSeleccionado);
            //navega a pantalla de procesamiento
            javax.swing.JOptionPane.showMessageDialog(this, "Se procesaran " + eventoTemp.cantRegistro() + " lineas del archivo.", "Importacion Exitosa", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            //pasa registro temporal a procesamiento y motor de reglas
            new PanelProcesamiento(eventoTemp).setVisible(true);
            this.dispose(); //cierra esta pantalla   
        } catch (Exception ex){
            javax.swing.JOptionPane.showMessageDialog(this, "Error durante la importacion: " + ex.getMessage(),
                    "Error de Archivo", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnConfirmarProcesarActionPerformed

