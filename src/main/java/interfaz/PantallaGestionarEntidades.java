    private void btnBuscarPersonaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarPersonaActionPerformed
        String dni = txtDni.getText().trim();
        if (dni.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un DNI para buscar.", "Atencion", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        DefaultListModel<String> modeloLista = new DefaultListModel<>();
        try{
           Persona persona = personaDAO.buscarPorDni(dni);
         if (persona != null){
             modeloLista.addElement("DNI: " + persona.getDni() + " - " + persona.getNombre() + " " + persona.getApellido() + " (Estado: " + (persona.isEstado() ? "Activo" : "Inactivo") + ")");
          } else {
             modeloLista.addElement("No se encontro ninguna persona con el DNI ingresado.");
         }
        } catch (AccesoDatosException e){
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        listaResultados.setModel(modeloLista);
    }//GEN-LAST:event_btnBuscarPersonaActionPerformed

    private void btnBuscarAreaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarAreaActionPerformed
        String criterioArea = txtArea.getText().trim();
        DefaultListModel<String> modeloLista = new DefaultListModel<>();
        try{
            List<Area> areas = areaDAO.listarTodas();
            boolean encontrado = false;
            for (Area a : areas){
                if (criterioArea.isEmpty() || a.getNombreArea().toLowerCase().contains(criterioArea.toLowerCase())){
                    modeloLista.addElement("Area: " + a.getNombreArea() + "(Nivel de Restriccion: " + a.getNivelRestriccion() + ")");
                    encontrado = true;
                }
            }
            if (!encontrado){
                modeloLista.addElement("No se encontraron areas coincidentes.");
            }
        } catch (AccesoDatosException e){
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        listaResultados.setModel(modeloLista);
    }//GEN-LAST:event_btnBuscarAreaActionPerformed


