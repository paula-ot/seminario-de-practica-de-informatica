    //carga las areas en el combo
    private void configurarEstadoInicial(){
        cbArea.removeAllItems();
        areas = new java.util.ArrayList<>();
        try{
        areas = new persistencia.AreaDAO().listarTodas();
        for (modelo.Area a : areas){
            cbArea.addItem(a.getNombreArea());
        }
    } catch (AccesoDatosException ex){
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }

