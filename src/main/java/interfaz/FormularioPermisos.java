    public FormularioPermisos(int idPersona, String nombrePersona){
        this.idPersona = idPersona;
        this.nombrePersona = nombrePersona;
        this.esEdicion = false;
        initComponents();
        inicializar();
    }

    //constructor para editar un permiso existente
    public FormularioPermisos(int idPermiso, int idPersona, String nombrePersona, String area,
            String fechaInicio, String fechaFin, String uidTarjeta) {
        this.idPermiso = idPermiso;
        this.idPersona = idPersona;
        this.nombrePersona = nombrePersona;
        this.esEdicion = true;
        initComponents();
        inicializar();
        cargarDatosParaEdicion(area, fechaInicio, fechaFin, uidTarjeta);
    }

    private void inicializar() {
        setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
        setLocationRelativeTo(null);
        jLabel1.setText("Permisos de: " + nombrePersona);
        configurarEstadoInicial();
        btnConfirmar.addActionListener(this::btnConfirmarActionPerformed);
        btnVolver.addActionListener(e -> dispose());
    }

    private void cargarDatosParaEdicion(String area, String fechaInicio, String fechaFin, String uidTarjeta) {
        setTitle("Editar Permiso de: " + nombrePersona);
        cbArea.setSelectedItem(area);
        txtInicio.setText(fechaInicio);
        txtFin.setText(fechaFin);
        txtTarjeta.setText(uidTarjeta);
        btnConfirmar.setText("Guardar Cambios");
    }
    //valida los datos y crea el permiso. si es edicion se crea el nuevo y revoca el anterior
    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            java.time.format.DateTimeFormatter f = java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
            java.time.LocalDateTime inicio = java.time.LocalDateTime.parse(txtInicio.getText().trim(), f);
            java.time.LocalDateTime fin = java.time.LocalDateTime.parse(txtFin.getText().trim(), f);
            String uid = txtTarjeta.getText().trim();
            if (uid.isEmpty() || cbArea.getSelectedIndex() < 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Complete el área y el UID de la tarjeta.",
                        "Campos requeridos", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            int idArea = areas.get(cbArea.getSelectedIndex()).getIdArea();
            boolean ok = controlador.crearPermiso(idPersona, idArea, uid, inicio, fin);
            if (ok && esEdicion) {
                controlador.revocarPermiso(idPermiso); //editar = crear el nuevo y revocar el anterior
            }
            javax.swing.JOptionPane.showMessageDialog(this, ok ? "Permiso guardado." : "No se pudo guardar el permiso.");
            if (ok) {
                dispose();
            }
        } catch (java.time.format.DateTimeParseException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de fecha inválido (yyyy-MM-dd HH:mm:ss).",
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

