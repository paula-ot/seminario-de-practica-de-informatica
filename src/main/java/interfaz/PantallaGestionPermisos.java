    //la busqueda debe dar exactamente una persona. si hay varias se refina
    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {
        String dni = txtDni.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellido.getText().trim();
        if (dni.isEmpty() && nombre.isEmpty() && apellido.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese al menos un criterio de búsqueda (DNI, nombre o apellido).", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        List<Persona> personas;
        try{
            personas = personaDAO.buscarPersonas(dni, nombre, apellido);
        } catch (AccesoDatosException e){
            personaActual = null;
            limpiarResultados("No se pudo consultar la base de datos.");
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (personas.isEmpty()) {
            personaActual = null;
            limpiarResultados("No se encontró ninguna persona con esos datos.");
            return;
        }
        if (personas.size() > 1) {
            personaActual = null;
            limpiarResultados("Hay " + personas.size() + " personas que coinciden. Refine la búsqueda con el DNI.");
            return;
        }
        personaActual = personas.get(0);
        cargarPermisos();
    }

    //carga la lista con los permisos activos de la persona. permisosMostrados guarda los objetos en el orden de la lista
    private void cargarPermisos(){
        try{
            permisosMostrados = permisoDAO.buscarPermisosPorDni(personaActual.getDni());
        } catch (AccesoDatosException e){
            limpiarResultados("No se pudo consultar la base de datos.");
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        DefaultListModel<String> modelo = new DefaultListModel<>();
        for (Permiso p : permisosMostrados) {
            String uid = (p.getTarjeta() != null) ? p.getTarjeta().getCodigoUID() : "sin tarjeta";
            modelo.addElement(p.getArea().getNombreArea() + " | " + p.getFechaInicio().format(FMT)
                    + " a " + p.getFechaFin().format(FMT) + " | Tarjeta: " + uid);
        }
        if (permisosMostrados.isEmpty()) {
            modelo.addElement("La persona no tiene permisos activos.");
        }
        listResultados.setModel(modelo);
        jLabel6.setText("Permisos de: " + personaActual.getNombreCompleto());
        btnNuevo.setEnabled(true);
        btnEditar.setEnabled(false);
        btnEliminar.setEnabled(false);
    }

    private void limpiarResultados(String mensaje) {
        permisosMostrados = new ArrayList<>();
        DefaultListModel<String> modelo = new DefaultListModel<>();
        modelo.addElement(mensaje);
        listResultados.setModel(modelo);
        jLabel6.setText("Resultados");
        btnNuevo.setEnabled(false);
        btnEditar.setEnabled(false);
        btnEliminar.setEnabled(false);
    }

    //devuelve el permiso seleccionado en la lista, o null si no hay
    private Permiso permisoSeleccionado(){
        int i = listResultados.getSelectedIndex();
        return (i >= 0 && i < permisosMostrados.size()) ? permisosMostrados.get(i) : null;
    }

    //abre el formulario y recarga la lista cuando se cierra
    private void mostrarFormulario(FormularioPermisos form){
        form.addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                if (personaActual != null) {
                    cargarPermisos();
                }
            }
        });
        form.setVisible(true);
    }

    private void btnNuevoActionPerformed(java.awt.event.ActionEvent evt){
        if (personaActual == null) {
            return;
        }
        if (!personaActual.isEstado()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La persona está inactiva, no se le pueden asignar permisos.",
                    "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        mostrarFormulario(new FormularioPermisos(personaActual.getIdPersona(), personaActual.getNombreCompleto()));
    }
    //abre el formulario con los datos actuales. Al confirmar se crea un nuevvo permiso y revoca el anterior
    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {
        Permiso p = permisoSeleccionado();
        if (p == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un permiso de la lista para editar.",
                    "Selección requerida", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        String uid = (p.getTarjeta() != null) ? p.getTarjeta().getCodigoUID() : "";
        mostrarFormulario(new FormularioPermisos(p.getIdPermiso(), personaActual.getIdPersona(),
                personaActual.getNombreCompleto(), p.getArea().getNombreArea(),
                p.getFechaInicio().format(FMT), p.getFechaFin().format(FMT), uid));
    }
    //baja logica, el registro no se borra
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {
        Permiso p = permisoSeleccionado();
        if (p == null) {
            return;
        }
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, "¿Revocar el permiso seleccionado?", "Confirmar revocación", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            try{
                if (controladorPermisos.revocarPermiso(p.getIdPermiso())) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Permiso revocado exitosamente.");
                    cargarPermisos();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error al revocar el permiso", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            } catch (AccesoDatosException e){
                javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }

