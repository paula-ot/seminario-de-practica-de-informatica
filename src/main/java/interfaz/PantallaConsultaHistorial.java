    //genera el reporte de asistencia y ofrece guardarlo en archivo de texto
    private void btnReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReporteActionPerformed
        try{
            String iniStr = txtFechaInicio.getText().trim();
            String finStr = txtFechaFin.getText().trim();
            if (iniStr.isEmpty() || finStr.isEmpty()){
                javax.swing.JOptionPane.showMessageDialog(this, "Las fechas de inicio y fin son obligatorias para el reporte (Formato: yyyy-MM-dd HH:mm:ss).", "Campos Requeridos", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            LocalDateTime inicio = LocalDateTime.parse(iniStr, formatter);
            LocalDateTime fin = LocalDateTime.parse(finStr, formatter);
            if (fin.isBefore(inicio)) {
                javax.swing.JOptionPane.showMessageDialog(this, "La fecha fin debe ser posterior a la de inicio.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            String area = cbArea.getSelectedItem() != null ? cbArea.getSelectedItem().toString() : "";
            String tarjeta = txtTarjeta.getText().trim();
            
            //genera reporte
            List<RegistroAsistencia> registros = controladorReportes.generarAsistencia(inicio, fin, area, tarjeta);
            mostrarReporteAsistencia(registros);
            if (registros.isEmpty()){
                javax.swing.JOptionPane.showMessageDialog(this, "No hay registros de asistencia en este periodo.", "Reporte", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            int opcion = javax.swing.JOptionPane.showConfirmDialog(this, "Se generaron " + registros.size() + "registros de asistencia. \n¿Desea guardar el reporte en un archivo de texto?", "Reporte de asistencia", javax.swing.JOptionPane.YES_NO_OPTION);
            if (opcion == javax.swing.JOptionPane.YES_OPTION){
                guardarReporte(registros, inicio, fin);
            }
        }catch (java.time.format.DateTimeParseException e){
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de fecha invalido. Formato requerido: yyyy-MM-dd HH:mm:ss", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (AccesoDatosException e){
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (Exception e){
            javax.swing.JOptionPane.showMessageDialog(this, "Error al generar el reporte: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
            
    //muestra el reporte en la tabla
    private void mostrarReporteAsistencia(List<RegistroAsistencia> registros){
        String[] columnas = {"Persona", "Fecha", "Ingreso", "Egreso", "Horas"};
        DefaultTableModel model = new DefaultTableModel(columnas, 0);
        for (RegistroAsistencia r : registros){
            model.addRow(r.aFila());
        }
        tablaHistorial.setModel(model);
    }
    
    //abre el selector de archivos y exporta el reporte con ControladorReportes
    private void guardarReporte(List<RegistroAsistencia> registros, LocalDateTime inicio, LocalDateTime fin){
        javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
        selector.setDialogTitle("Guardar reporte de asistencia");
        selector.setSelectedFile(new java.io.File("reporte_asistencia_" + java.time.LocalDate.now() + ".txt"));
        if (selector.showSaveDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION){
            try{
                controladorReportes.exportarAArchivo(registros, inicio, fin, selector.getSelectedFile());
                javax.swing.JOptionPane.showMessageDialog(this, "Reporte guardado en:\n" + selector.getSelectedFile().getAbsolutePath());
            } catch (java.io.IOException e){
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo guardar el archivo: " + e.getMessage(), "Error de archivo", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnReporteActionPerformed
    
