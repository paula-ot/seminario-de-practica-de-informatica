    private void actualizarTablaResultados(List<Object[]> datos){
        String[] columnas = {"UID", "FechaHora", "Area", "Persona"};
        DefaultTableModel model  = new DefaultTableModel(columnas, 0);
        for (Object[] fila : datos){
            model.addRow(fila);
        }
        tablaHistorial.setModel(model);
    }

