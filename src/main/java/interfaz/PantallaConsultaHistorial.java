                javax.swing.JOptionPane.showMessageDialog(this, "Las fechas de inicio y fin son obligatorias (Formato: yyyy-MM-dd HH:mm:ss).", "Campos Requeridos", javax.swing.JOptionPane.WARNING_MESSAGE);
