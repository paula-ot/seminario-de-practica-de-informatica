    //ejecuta el motor de reglas al abrir el panel
    private void ejecutarProcesamiento(){
        if (registroTemp != null){
            try{
            //obtiene metricas
            //totalProcesados, totalValidos, totalAlertas
            int[] metricas = motorReglas.procesarEventos(registroTemp);
            //cuenta lineas con errores
            int errores = metricas[0] - metricas[1] - metricas[2];
            //actualiza etiqueta de resumen
            lblResumenMetricas.setText("Eventos procesados: " + metricas[0] + " | Válidos: " + metricas[1] + " | Alertas generadas: " + metricas[2] + (errores > 0 ? " | Con error: " + errores : ""));
            //cargar tabla de alertas generadas
            cargarTablaAlertas(); 
            } catch (AccesoDatosException e){
                lblResumenMetricas.setText("El procesamiento se interrumpió por un error de base de datos");
                javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Error de base de datos", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }
    
    //muestra las alertas del archivo recien procesado filtrando por idArchivoLog. es una consulta a la base
    private void cargarTablaAlertas(){
        String[] columnas = {"UID", "FechaHora", "Lector", "Gravedad", "Area", "Tipo"};
        DefaultTableModel model = new DefaultTableModel(columnas, 0);
        String sql = "SELECT e.codigoLeido, e.fechaHora, c.codigoLector, al.nivelGravedad, " 
                + "COALESCE(a.nombreArea, 'General') AS nombreArea, al.tipoAnomalia FROM Alerta al " 
                + "JOIN Evento e ON al.idEvento = e.idEvento LEFT JOIN Cerradura c ON e.idCerradura = c.idCerradura " 
                + "LEFT JOIN Area a ON c.idArea = a.idArea WHERE e.idArchivoLog = ? ORDER BY e.fechaHora DESC";
        try (Connection con = ConexionBD.getConexion();
        PreparedStatement ps = con.prepareStatement(sql)){
        ps.setInt(1, registroTemp.getArchivoLog().getIdArchivo());
        try (ResultSet rs = ps.executeQuery()){
            while (rs.next()){
                Object[] fila = new Object[]{
                    rs.getString("codigoLeido"),
                    rs.getTimestamp("fechaHora").toString(),
                    rs.getString("codigoLector"),
                    rs.getString("nivelGravedad"),
                    rs.getString("nombreArea"),
                    rs.getString("tipoAnomalia")};
                model.addRow(fila);
            }
        }
        } catch (SQLException e){
               javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar las alertas: " + e.getMessage());
        }
        tablaAlertas.setModel(model);
    }
    
